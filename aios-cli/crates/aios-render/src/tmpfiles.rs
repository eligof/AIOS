use aios_manifest::Manifest;
use std::collections::{BTreeMap, BTreeSet};

const HEADER: &str = "# Generated by aios. Do not edit: /etc is reset at every boot.\n";

/// Escape one tmpfiles.d path or argument field so systemd-tmpfiles reads back exactly `s`
/// as a single field: `\` becomes `\\`, `%` becomes `%%` (no specifier expansion), and
/// whitespace, ASCII control characters and quotes become `\xNN` (lowercase hex).
pub fn tmpfiles_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '%' => out.push_str("%%"),
            c if c.is_ascii_whitespace() || c.is_ascii_control() || c == '"' || c == '\'' => {
                out.push_str(&format!("\\x{:02x}", u32::from(c)));
            }
            c => out.push(c),
        }
    }
    out
}

/// `/etc/tmpfiles.d/aios-persist.conf`: each declared persistent file becomes a symlink
/// into `/persist` (spec §3 step 10).
pub fn persist_tmpfiles(m: &Manifest) -> String {
    let mut out = String::from(HEADER);
    for file in &m.persist.files {
        out.push_str(&format!(
            "L+ {} - - - - {}\n",
            tmpfiles_escape(file),
            tmpfiles_escape(&format!("/persist{file}"))
        ));
    }
    out
}

/// `/etc/tmpfiles.d/aios-home.conf` (spec §4.4): `d` lines, sorted and unique, owned by the
/// user, for each declared user's home (`0700`) and every directory between the home and a
/// `[users.<u>.home]` target (`0700` at or under `~/.ssh`, else `0755`).
///
/// Targets are never listed, not even as the parent of another target: systemd creates the
/// mount points, before tmpfiles runs and as root, which is why the parents are listed here
/// (`d` fixes their owner and mode). A `d` or `f` line for a target would hit the read-only
/// bind on every later boot (EROFS).
pub fn home_tmpfiles(m: &Manifest) -> String {
    let mut dirs: BTreeMap<String, (&str, &str)> = BTreeMap::new();
    for (user, u) in &m.users {
        let home = format!("/home/{user}");
        let targets: BTreeSet<&str> = u.home.keys().map(|k| k.trim_end_matches('/')).collect();
        for key in u.home.keys() {
            let parts: Vec<&str> = key.trim_end_matches('/').split('/').collect();
            let mode = if parts[0] == ".ssh" { "0700" } else { "0755" };
            for depth in 1..parts.len() {
                let rel = parts[..depth].join("/");
                if !targets.contains(rel.as_str()) {
                    dirs.insert(format!("{home}/{rel}"), (user.as_str(), mode));
                }
            }
        }
        dirs.insert(home, (user.as_str(), "0700"));
    }
    let mut out = String::from(HEADER);
    for (dir, (user, mode)) in dirs {
        out.push_str(&format!(
            "d {} {mode} {user} {user} -\n",
            tmpfiles_escape(&dir)
        ));
    }
    out
}

/// A package-owned path outside the generation that the next boot's root (a fresh copy of
/// `@blank`) lacks, as found in the candidate after the packages step.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub enum PackagePath {
    Dir {
        path: String,
        mode: u32,
        uid: u32,
        gid: u32,
    },
    Symlink {
        path: String,
        target: String,
    },
}

impl PackagePath {
    fn path(&self) -> &str {
        match self {
            PackagePath::Dir { path, .. } | PackagePath::Symlink { path, .. } => path,
        }
    }
}

/// `/etc/tmpfiles.d/zz-aios-pkgdirs.conf` (spec §4.3 step 5): recreates at every boot the
/// package-owned directories (`d`, with the package's mode and numeric owner) and symlinks
/// (`L`, which leaves an existing path alone) that live outside `/usr` and `/etc`. Sorted by
/// path; a path given twice is written once.
pub fn pkgdirs_tmpfiles(paths: &[PackagePath]) -> String {
    let mut sorted: Vec<&PackagePath> = paths.iter().collect();
    sorted.sort_by(|a, b| a.path().cmp(b.path()).then(a.cmp(b)));
    sorted.dedup_by(|a, b| a.path() == b.path());
    let mut out = String::from(HEADER);
    for entry in sorted {
        let line = match entry {
            PackagePath::Dir {
                path,
                mode,
                uid,
                gid,
            } => format!("d {} {mode:04o} {uid} {gid} -\n", tmpfiles_escape(path)),
            PackagePath::Symlink { path, target } => format!(
                "L {} - - - - {}\n",
                tmpfiles_escape(path),
                tmpfiles_escape(target)
            ),
        };
        out.push_str(&line);
    }
    out
}

/// Read back what [`pkgdirs_tmpfiles`] wrote, by path. Comments, blank lines and any line it
/// can't have written are skipped.
pub fn parse_pkgdirs_tmpfiles(text: &str) -> BTreeMap<String, PackagePath> {
    text.lines()
        .filter_map(parse_pkgdirs_line)
        .map(|entry| (entry.path().to_string(), entry))
        .collect()
}

fn parse_pkgdirs_line(line: &str) -> Option<PackagePath> {
    let fields: Vec<&str> = line.split_ascii_whitespace().collect();
    let octal = |s: &str| s.len() == 4 && s.bytes().all(|b| (b'0'..=b'7').contains(&b));
    let decimal = |s: &str| !s.is_empty() && s.bytes().all(|b| b.is_ascii_digit());
    match fields.as_slice() {
        ["d", path, mode, uid, gid, "-"] if octal(mode) && decimal(uid) && decimal(gid) => {
            Some(PackagePath::Dir {
                path: absolute(path)?,
                mode: u32::from_str_radix(mode, 8).ok()?,
                uid: uid.parse().ok()?,
                gid: gid.parse().ok()?,
            })
        }
        ["L", path, "-", "-", "-", "-", target] => Some(PackagePath::Symlink {
            path: absolute(path)?,
            target: tmpfiles_unescape(target)?,
        }),
        _ => None,
    }
}

/// An escaped path field that names an absolute path.
fn absolute(field: &str) -> Option<String> {
    tmpfiles_unescape(field).filter(|path| path.starts_with('/'))
}

/// The inverse of [`tmpfiles_escape`]; `None` for anything it can't have produced.
fn tmpfiles_unescape(s: &str) -> Option<String> {
    let mut out = String::with_capacity(s.len());
    let mut chars = s.chars();
    while let Some(c) = chars.next() {
        match c {
            '\\' => match chars.next()? {
                '\\' => out.push('\\'),
                'x' => {
                    let hex: String = chars.by_ref().take(2).collect();
                    if hex.len() != 2 || !hex.chars().all(|h| h.is_ascii_hexdigit()) {
                        return None;
                    }
                    out.push(char::from(u8::from_str_radix(&hex, 16).ok()?));
                }
                _ => return None,
            },
            '%' if chars.next()? == '%' => out.push('%'),
            '%' => return None,
            c => out.push(c),
        }
    }
    Some(out)
}

/// Directories under `/persist` that must exist for the binds and symlinks to work:
/// each persistent directory plus the parent of each persistent file. Sorted, unique.
pub fn persist_dirs(m: &Manifest) -> Vec<String> {
    let mut dirs = BTreeSet::new();
    for dir in &m.persist.directories {
        dirs.insert(format!("/persist{dir}"));
    }
    for file in &m.persist.files {
        let parent = file.rfind('/').map_or("", |i| &file[..i]);
        dirs.insert(format!("/persist{parent}"));
    }
    dirs.into_iter().collect()
}
