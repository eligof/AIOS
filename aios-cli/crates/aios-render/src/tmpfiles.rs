use aios_manifest::Manifest;
use std::collections::{BTreeMap, BTreeSet};

const HEADER: &str = "# Generated by aios. Do not edit: /etc is reset at every boot.\n";

/// Escape one tmpfiles.d path or argument field so systemd-tmpfiles reads back exactly `s`
/// as a single field: `\` becomes `\\`, `%` becomes `%%` (no specifier expansion), and
/// whitespace, ASCII control characters and quotes become `\xNN` (lowercase hex).
pub fn tmpfiles_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '%' => out.push_str("%%"),
            c if c.is_ascii_whitespace() || c.is_ascii_control() || c == '"' || c == '\'' => {
                out.push_str(&format!("\\x{:02x}", u32::from(c)));
            }
            c => out.push(c),
        }
    }
    out
}

/// `/etc/tmpfiles.d/aios-persist.conf`: each declared persistent file becomes a symlink
/// into `/persist` (spec §3 step 10).
pub fn persist_tmpfiles(m: &Manifest) -> String {
    let mut out = String::from(HEADER);
    for file in &m.persist.files {
        out.push_str(&format!(
            "L+ {} - - - - {}\n",
            tmpfiles_escape(file),
            tmpfiles_escape(&format!("/persist{file}"))
        ));
    }
    out
}

/// `/etc/tmpfiles.d/aios-home.conf` (spec §4.4): `d` lines, sorted and unique, owned by the
/// user, for each declared user's home (`0700`) and every directory between the home and a
/// `[users.<u>.home]` target (`0700` at or under `~/.ssh`, else `0755`).
///
/// Targets are never listed, not even as the parent of another target: systemd creates the
/// mount points, before tmpfiles runs and as root, which is why the parents are listed here
/// (`d` fixes their owner and mode). A `d` or `f` line for a target would hit the read-only
/// bind on every later boot (EROFS).
pub fn home_tmpfiles(m: &Manifest) -> String {
    let mut dirs: BTreeMap<String, (&str, &str)> = BTreeMap::new();
    for (user, u) in &m.users {
        let home = format!("/home/{user}");
        let targets: BTreeSet<&str> = u.home.keys().map(|k| k.trim_end_matches('/')).collect();
        for key in u.home.keys() {
            let parts: Vec<&str> = key.trim_end_matches('/').split('/').collect();
            let mode = if parts[0] == ".ssh" { "0700" } else { "0755" };
            for depth in 1..parts.len() {
                let rel = parts[..depth].join("/");
                if !targets.contains(rel.as_str()) {
                    dirs.insert(format!("{home}/{rel}"), (user.as_str(), mode));
                }
            }
        }
        dirs.insert(home, (user.as_str(), "0700"));
    }
    let mut out = String::from(HEADER);
    for (dir, (user, mode)) in dirs {
        out.push_str(&format!(
            "d {} {mode} {user} {user} -\n",
            tmpfiles_escape(&dir)
        ));
    }
    out
}

/// Directories under `/persist` that must exist for the binds and symlinks to work:
/// each persistent directory plus the parent of each persistent file. Sorted, unique.
pub fn persist_dirs(m: &Manifest) -> Vec<String> {
    let mut dirs = BTreeSet::new();
    for dir in &m.persist.directories {
        dirs.insert(format!("/persist{dir}"));
    }
    for file in &m.persist.files {
        let parent = file.rfind('/').map_or("", |i| &file[..i]);
        dirs.insert(format!("/persist{parent}"));
    }
    dirs.into_iter().collect()
}
