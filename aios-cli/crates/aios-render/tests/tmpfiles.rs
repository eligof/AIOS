fn dir(path: &str, mode: u32, uid: u32, gid: u32) -> PackagePath {
    PackagePath::Dir {
        path: path.to_string(),
        mode,
        uid,
        gid,
    }
}

/// `zz-aios-pkgdirs.conf` (spec §4.3 step 5): a `d` line with the package's mode and numeric
/// owner per directory, an `L` line per symlink, sorted by path and unique.
#[test]
fn pkgdirs_tmpfiles_recreates_directories_and_symlinks() {
    let paths = [
        dir("/var/spool/mail", 0o1777, 0, 12),
        PackagePath::Symlink {
            path: "/var/mail".to_string(),
            target: "spool/mail".to_string(),
        },
        dir("/srv/ftp", 0o555, 0, 11),
        dir("/opt", 0o755, 0, 0),
        dir("/srv/ftp", 0o555, 0, 11),
    ];
    let expected = format!(
        "{HEADER}d /opt 0755 0 0 -\n\
         d /srv/ftp 0555 0 11 -\n\
         L /var/mail - - - - spool/mail\n\
         d /var/spool/mail 1777 0 12 -\n"
    );
    assert_eq!(pkgdirs_tmpfiles(&paths), expected);
}

#[test]
fn pkgdirs_tmpfiles_escapes_paths_and_targets() {
    let paths = [
        dir("/opt/a b%", 0o755, 0, 0),
        PackagePath::Symlink {
            path: "/srv/x\ny".to_string(),
            target: "../t z".to_string(),
        },
    ];
    let expected = format!(
        "{HEADER}d /opt/a\\x20b%% 0755 0 0 -\n\
         L /srv/x\\x0ay - - - - ../t\\x20z\n"
    );
    assert_eq!(pkgdirs_tmpfiles(&paths), expected);
    assert_eq!(pkgdirs_tmpfiles(&[]), HEADER);
}

/// apply carries the booted generation's lines over for packages it doesn't reinstall, so
/// what `pkgdirs_tmpfiles` writes reads back as the same paths.
#[test]
fn parse_pkgdirs_tmpfiles_reads_back_what_was_rendered() {
    let paths = vec![
        dir("/opt/a b%\\c\"'", 0o2755, 0, 50),
        PackagePath::Symlink {
            path: "/srv/x\ny".to_string(),
            target: "../t z%".to_string(),
        },
        dir("/var/spool/mail", 0o1777, 0, 12),
    ];
    let parsed = parse_pkgdirs_tmpfiles(&pkgdirs_tmpfiles(&paths));
    let expected: Vec<(String, PackagePath)> = paths
        .iter()
        .map(|p| match p {
            PackagePath::Dir { path, .. } | PackagePath::Symlink { path, .. } => {
                (path.clone(), p.clone())
            }
        })
        .collect();
    let mut expected = expected;
    expected.sort();
    assert_eq!(parsed.into_iter().collect::<Vec<_>>(), expected);
}

#[test]
fn parse_pkgdirs_tmpfiles_skips_lines_it_did_not_write() {
    let text = format!(
        "{HEADER}\n# comment\nd /opt 0755 0 0 -\n\
         d /bad 0999 0 0 -\nd /short 0755 0\nf /file 0644 0 0 -\n\
         L /odd%x - - - - t\nd /trail\\ 0755 0 0 -\nd relative 0755 0 0 -\n"
    );
    let parsed = parse_pkgdirs_tmpfiles(&text);
    assert_eq!(
        parsed.into_iter().collect::<Vec<_>>(),
        [("/opt".to_string(), dir("/opt", 0o755, 0, 0))]
    );
}
