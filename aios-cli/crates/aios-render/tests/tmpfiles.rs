mod common;

use aios_render::{home_tmpfiles, persist_dirs, persist_tmpfiles, tmpfiles_escape};
use common::{manifest, manifest_from, MANIFEST};

const HEADER: &str = "# Generated by aios. Do not edit: /etc is reset at every boot.\n";
const FILES_LINE: &str = "files = [\"/etc/machine-id\", \"/var/lib/systemd/random-seed\"]";

#[test]
fn persist_tmpfiles_links_each_file_into_persist() {
    let expected = format!(
        "{HEADER}L+ /etc/machine-id - - - - /persist/etc/machine-id\n\
         L+ /var/lib/systemd/random-seed - - - - /persist/var/lib/systemd/random-seed\n"
    );
    assert_eq!(persist_tmpfiles(&manifest()), expected);
}

#[test]
fn home_tmpfiles_creates_the_home_and_bind_parents_only() {
    let expected = format!(
        "{HEADER}d /home/eli 0700 eli eli -\n\
         d /home/eli/.config 0755 eli eli -\n"
    );
    assert_eq!(home_tmpfiles(&manifest()), expected);
}

#[test]
fn home_tmpfiles_parents_are_sorted_unique_and_ssh_is_private() {
    let raw = MANIFEST
        .replace(
            "\".zshrc\" = \"home/eli/zshrc\"",
            "\".zshrc\" = \"home/eli/zshrc\"\n\
             \".config/systemd/user/\" = \"home/eli/systemd-user/\"\n\
             \".ssh/authorized_keys\" = \"home/eli/authorized_keys\"\n\
             \".local/bin/\" = \"home/eli/bin/\"",
        )
        .replace(
            "[users.eli]",
            "[users.ada]\nuid = 1001\nshell = \"/usr/bin/bash\"\n\n\
             [users.bob]\nuid = 1002\nshell = \"/usr/bin/bash\"\n\n\
             [users.bob.home]\n\".local/share/a/b\" = \"home/bob/b\"\n\n\
             [users.eli]",
        );
    let expected = format!(
        "{HEADER}\
         d /home/ada 0700 ada ada -\n\
         d /home/bob 0700 bob bob -\n\
         d /home/bob/.local 0755 bob bob -\n\
         d /home/bob/.local/share 0755 bob bob -\n\
         d /home/bob/.local/share/a 0755 bob bob -\n\
         d /home/eli 0700 eli eli -\n\
         d /home/eli/.config 0755 eli eli -\n\
         d /home/eli/.config/systemd 0755 eli eli -\n\
         d /home/eli/.local 0755 eli eli -\n\
         d /home/eli/.ssh 0700 eli eli -\n"
    );
    assert_eq!(home_tmpfiles(&manifest_from(&raw)), expected);
}

#[test]
fn tmpfiles_escape_rules() {
    let cases = [
        ("/plain/path", "/plain/path"),
        ("/a b", "/a\\x20b"),
        ("/a\tb", "/a\\x09b"),
        ("/a\nb", "/a\\x0ab"),
        ("/a\rb", "/a\\x0db"),
        ("/a\u{0}b", "/a\\x00b"),
        ("/a\u{1b}b", "/a\\x1bb"),
        ("/a\u{7f}b", "/a\\x7fb"),
        ("/100%", "/100%%"),
        ("/%h", "/%%h"),
        ("/a\\b", "/a\\\\b"),
        ("/a\"b", "/a\\x22b"),
        ("/a'b", "/a\\x27b"),
        ("/caf\u{e9}", "/caf\u{e9}"),
    ];
    for (raw, escaped) in cases {
        assert_eq!(tmpfiles_escape(raw), escaped, "input {raw:?}");
    }
}

#[test]
fn persist_tmpfiles_escapes_each_path_into_one_line() {
    let cases = [
        (r"/var/lib/a\nb", r"/var/lib/a\x0ab"),
        (r"/var/lib/a b", r"/var/lib/a\x20b"),
        (r"/var/lib/%h", r"/var/lib/%%h"),
        (r"/var/lib/a\\b", r"/var/lib/a\\b"),
    ];
    for (toml, escaped) in cases {
        let m = manifest_from(&MANIFEST.replace(FILES_LINE, &format!("files = [\"{toml}\"]")));
        let expected = format!("{HEADER}L+ {escaped} - - - - /persist{escaped}\n");
        let text = persist_tmpfiles(&m);
        assert_eq!(text, expected, "path {toml}");
        assert_eq!(text.lines().count(), 2, "got {text:?}");
    }
}

#[test]
fn home_tmpfiles_escapes_each_path_into_one_line() {
    let cases = [
        (r"a\nb", r"a\x0ab"),
        (r"a b", r"a\x20b"),
        (r"%h", r"%%h"),
        (r"a\\b", r"a\\b"),
    ];
    for (toml, escaped) in cases {
        let m = manifest_from(&MANIFEST.replace(
            "\".config/autostart/\" =",
            &format!("\"{toml}/autostart/\" ="),
        ));
        let expected =
            format!("{HEADER}d /home/eli 0700 eli eli -\nd /home/eli/{escaped} 0755 eli eli -\n");
        let text = home_tmpfiles(&m);
        assert_eq!(text, expected, "key {toml}");
        assert_eq!(text.lines().count(), 3, "got {text:?}");
    }
}

#[test]
fn empty_lists_render_header_only() {
    let raw = MANIFEST.replace(FILES_LINE, "files = []");
    let m = manifest_from(raw.split("[users.eli]").next().unwrap());
    assert_eq!(persist_tmpfiles(&m), HEADER);
    assert_eq!(home_tmpfiles(&m), HEADER);
}

#[test]
fn persist_dirs_cover_directories_and_file_parents() {
    assert_eq!(
        persist_dirs(&manifest()),
        [
            "/persist/etc",
            "/persist/var/cache/pacman/pkg",
            "/persist/var/lib/NetworkManager",
            "/persist/var/lib/systemd",
        ]
    );
}

#[test]
fn persist_dirs_handle_top_level_files_and_duplicates() {
    let raw = MANIFEST.replace(
        FILES_LINE,
        "files = [\"/etc/machine-id\", \"/etc/adjtime\", \"/top-level\"]",
    );
    assert_eq!(
        persist_dirs(&manifest_from(&raw)),
        [
            "/persist",
            "/persist/etc",
            "/persist/var/cache/pacman/pkg",
            "/persist/var/lib/NetworkManager",
        ]
    );
}
